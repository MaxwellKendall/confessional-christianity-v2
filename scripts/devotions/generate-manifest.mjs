#!/usr/bin/env node
// Generates src/lib/devotionManifest.generated.ts: one static import per
// content/devotions/*.json and content/devotions/series/*.json. Static
// imports keep the bundler tracing the data (a dynamic fs read breaks in
// Vercel's serverless bundles — see programContent.ts), and generating them
// means a new devotion is just a new JSON file: nobody (and no /admin save)
// has to hand-edit a TypeScript import list. The output is gitignored and
// rebuilt by predev/prebuild/pretest/postinstall, so two devotions authored
// on two branches never conflict over it.
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const devotionsDir = path.join(repoRoot, 'content/devotions');
const seriesDir = path.join(devotionsDir, 'series');
const output = path.join(repoRoot, 'src/lib/devotionManifest.generated.ts');

const jsonSlugs = async (dir) => (await fs.readdir(dir))
  .filter((name) => name.endsWith('.json'))
  .map((name) => name.slice(0, -'.json'.length))
  // natural order, so wsc-2 precedes wsc-10 and the list reads like the
  // hand-written one it replaced
  .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));

const identifier = (prefix, slug) => `${prefix}_${slug.replace(/[^A-Za-z0-9]/g, '_')}`;

const devotions = await jsonSlugs(devotionsDir);
const series = await jsonSlugs(seriesDir);

const lines = [
  '// GENERATED by scripts/devotions/generate-manifest.mjs — do not edit.',
  '// Run `npm run devotions:manifest` after adding a file under content/devotions.',
  ...devotions.map((slug) => `import ${identifier('devotion', slug)} from '../../content/devotions/${slug}.json';`),
  ...series.map((slug) => `import ${identifier('series', slug)} from '../../content/devotions/series/${slug}.json';`),
  '',
  'export const DEVOTION_JSON: unknown[] = [',
  ...devotions.map((slug) => `  ${identifier('devotion', slug)},`),
  '];',
  '',
  'export const SERIES_JSON: unknown[] = [',
  ...series.map((slug) => `  ${identifier('series', slug)},`),
  '];',
  '',
];

const next = lines.join('\n');
const current = await fs.readFile(output, 'utf8').catch(() => null);
// skip identical rewrites so `next dev` doesn't see a spurious change
if (current !== next) await fs.writeFile(output, next, 'utf8');
console.log(`Devotion manifest: ${devotions.length} devotions, ${series.length} series`);
